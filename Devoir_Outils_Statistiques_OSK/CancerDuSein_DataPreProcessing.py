def make_num_imputer(kind):
    if kind == "median":
        return SimpleImputer(strategy="median", add_indicator=True)
    if kind == "knn":
        return KNNImputer(n_neighbors=5, add_indicator=True)
    if kind == "iterative":
        return IterativeImputer(max_iter=10, random_state=RANDOM_STATE,
                                add_indicator=True)
    raise ValueError(kind)

from enum import verify
def build_preprocessor(scale: bool):
  """scale=True pour SVM / modeles lineaires, False pour arbres."""
  sc = [("scale", StandardScaler())] if scale else []

  log_pipe = Pipeline([
    ("log", FunctionTransformer(np.log1p, feature_names_out="one-to-one")),
] + sc + [
    ("imp", make_num_imputer(NUM_IMPUTER)),
])

  lin_pipe = Pipeline(sc + [("imp", make_num_imputer(NUM_IMPUTER))])

  ord_num_pipe = Pipeline([
      ("imp", SimpleImputer(strategy="most_frequent")),
  ] + sc)

  ord_cat_pipe = Pipeline([
      ("imp", SimpleImputer(strategy="most_frequent")),
      ("ord", OrdinalEncoder(categories=[["Low", "Moderate", "High"]],
                             handle_unknown="use_encoded_value",
                             unknown_value=np.nan)),
      ("imp2", SimpleImputer(strategy="most_frequent")),
  ] + sc)

  bin_pipe = Pipeline([
       ("imp", SimpleImputer(strategy="constant", fill_value="Unknown")),
       ("ohe", OneHotEncoder(handle_unknown="ignore", drop="if_binary", sparse_output=False)),
   ])

  nom_pipe = Pipeline([
    ("imp", SimpleImputer(strategy="constant", fill_value="Unknown")),
    ("ohe", OneHotEncoder(handle_unknown="infrequent_if_exist",
                          min_frequency=RARE_THRESHOLD,
                          sparse_output=False)),
])

  eng_pipe = Pipeline([
      ("imp", SimpleImputer(strategy="most_frequent")),
  ])

  transformers = []
  if log_cols:
     transformers.append(("log", log_pipe, log_cols))
  if lin_cols:
    transformers.append(("lin", lin_pipe, lin_cols))
  if ordinal_num_cols:
    transformers.append(("ordnum", ord_num_pipe, ordinal_num_cols))
  if ordinal_cat_cols:
    transformers.append(("ordcat", ord_cat_pipe, ordinal_cat_cols))
  if binary_cols:
    transformers.append(("bin", bin_pipe, binary_cols))
  if nominal_cols:
    transformers.append(("nom", nom_pipe, nominal_cols))
  if engineered_cols:
    transformers.append(("eng", eng_pipe, engineered_cols))

  return ColumnTransformer(transformers, remainder="drop", verbose_feature_names_out=False)

